// Build the static site: the web UI plus core/.
//   node scripts/build-demo.js _site        GitHub Pages demo: the data source
//                                           switches to the in-browser tracker
//   node scripts/build-demo.js public api   Vercel: the UI talks to /api
import { cpSync, rmSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const out = resolve(process.argv[2] ?? '_site');
const mode = process.argv[3] ?? 'local';
const root = (p) => new URL(`../${p}`, import.meta.url);

rmSync(out, { recursive: true, force: true });
cpSync(root('web'), out, { recursive: true });
cpSync(root('core'), resolve(out, 'core'), { recursive: true });
if (mode === 'local') {
  writeFileSync(
    resolve(out, 'config.js'),
    "// Generated by scripts/build-demo.js\nexport const MODE = 'local';\n",
  );
  writeFileSync(resolve(out, '.nojekyll'), '');
}
console.log(`Site built in ${out} (${mode} mode)`);
